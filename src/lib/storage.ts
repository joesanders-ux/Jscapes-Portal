import "server-only";
import { mkdir, readFile, unlink, writeFile } from "node:fs/promises";
import path from "node:path";

/**
 * Persistent file storage on disk.
 *
 * Production: FILES_DIR must point at a mounted Railway Volume (for example /data/uploads).
 * Railway's normal filesystem is wiped on every deploy, so without a volume uploads would
 * silently vanish. For that reason uploads are REFUSED in production until FILES_DIR is set.
 * Local development falls back to ./.data (git-ignored).
 */
export function storageRoot(): string | null {
  const dir = process.env.FILES_DIR?.trim();
  if (dir) return path.resolve(dir);
  if (process.env.NODE_ENV === "production") return null;
  return path.resolve(process.cwd(), ".data");
}

export const MAX_PDF_BYTES = 15 * 1024 * 1024;

export const storageConfigured = () => storageRoot() !== null;

// Storage keys are generated by the app (uuid + .pdf). Anything else is rejected,
// so a key can never be used to reach outside the storage folder.
const KEY = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\.pdf$/;

function resolveKey(key: string): string {
  const root = storageRoot();
  if (!root) throw new Error("File storage is not configured (FILES_DIR).");
  if (!KEY.test(key)) throw new Error("Invalid storage key.");
  return path.join(root, key);
}

export async function saveFile(key: string, data: Buffer): Promise<void> {
  const target = resolveKey(key);
  await mkdir(path.dirname(target), { recursive: true });
  await writeFile(target, data, { flag: "wx" }); // never overwrite an existing file
}

export async function readStoredFile(key: string): Promise<Buffer> {
  return readFile(resolveKey(key));
}

export async function deleteFile(key: string): Promise<void> {
  try {
    await unlink(resolveKey(key));
  } catch {
    /* already gone */
  }
}
